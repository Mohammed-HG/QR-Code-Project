const path = require('node:path');
require('dotenv').config({ path: path.join(__dirname, '.env'), quiet: true });
function configFromEnv(env = process.env) {
  const production = env.NODE_ENV === 'production';
  const secret = env.AUTH_SECRET || '';
  if (!/^[a-f0-9]{64,}$/i.test(secret) || new Set(secret.toLowerCase()).size < 8) {
    throw new Error('AUTH_SECRET must contain at least 32 randomly generated bytes encoded as hex.');
  }
  const origin = env.APP_ORIGIN || 'http://localhost:3000';
  const parsed = new URL(origin);
  if (parsed.origin !== origin || !['http:', 'https:'].includes(parsed.protocol) ||
      (production && parsed.protocol !== 'https:' && parsed.hostname !== 'localhost')) {
    throw new Error('APP_ORIGIN must be an exact origin; production requires HTTPS.');
  }
  const port = Number(env.PORT || 3200);
  const trustProxyHops = Number(env.TRUST_PROXY_HOPS || 0);
  if (!Number.isInteger(port) || port < 1 || port > 65535 ||
      !Number.isInteger(trustProxyHops) || trustProxyHops < 0 || trustProxyHops > 2) {
    throw new Error('Invalid PORT or TRUST_PROXY_HOPS.');
  }
  return { production, port, origin, secret, trustProxyHops,
    cookieName: production ? '__Host-qr_session' : 'qr_session',
    sessionMs: 8 * 60 * 60 * 1000, otpMs: 5 * 60 * 1000, proofMs: 5 * 60 * 1000 };
}
module.exports = { configFromEnv };
