import React from 'react';
import { beforeEach, test, expect, vi } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import Generator from './Generator';
vi.mock('./LocationMap', () => ({ default: () => <div>Location map</div> }));
const png = () => new Response(new Blob(['png'], { type: 'image/png' }), { headers: { 'content-type': 'image/png' } });
beforeEach(() => { vi.stubGlobal('fetch', vi.fn(async () => png())); });
test('allows typing URLs and only generates when submitted', async () => {
  const user = userEvent.setup();
  render(<Generator />);
  await user.type(screen.getByLabelText('Website link'), 'https://example.com:8443/path?q=test');
  expect(fetch).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Generate QR code' }));
  await screen.findByRole('link', { name: 'Download PNG' });
  const payload = JSON.parse(fetch.mock.calls[0][1].body);
  expect(payload.kind).toBe('url');
  expect(payload.text).toContain('?q=test');
  expect(URL.createObjectURL).toHaveBeenCalledTimes(1);
});
test('Wi-Fi customization preserves network payload and clears stale downloads', async () => {
  const user = userEvent.setup();
  render(<Generator />);
  await user.type(screen.getByLabelText('Website link'), 'https://old.example');
  await user.click(screen.getByRole('button', { name: 'Generate QR code' }));
  await screen.findByRole('link', { name: 'Download PNG' });
  await user.click(screen.getByRole('button', { name: 'Wi-Fi', exact: true }));
  expect(screen.queryByRole('link', { name: 'Download PNG' })).toBeNull();
  await user.type(screen.getByLabelText('Network name (SSID)'), 'Office;network');
  await user.type(screen.getByLabelText('Wi-Fi password'), 'correct;secret');
  await user.selectOptions(screen.getByLabelText('Security type'), 'WEP');
  await user.click(screen.getByRole('button', { name: 'Generate QR code' }));
  await screen.findByRole('link', { name: 'Download PNG' });
  const payload = JSON.parse(fetch.mock.calls.at(-1)[1].body);
  expect(payload).toMatchObject({ kind: 'wifi', encryption: 'WEP', ssid: 'Office;network', password: 'correct;secret' });
  expect(payload.text).toBeUndefined();
  expect(URL.revokeObjectURL).toHaveBeenCalled();
});
test('changing settings cancels in-flight work and ignores stale responses', async () => {
  let resolve;
  fetch.mockImplementationOnce(() => new Promise(r => { resolve = r; }));
  const user = userEvent.setup();
  render(<Generator />);
  await user.type(screen.getByLabelText('Website link'), 'https://example.com');
  await user.click(screen.getByRole('button', { name: 'Generate QR code' }));
  expect(screen.getByRole('button', { name: 'Generating…' }).disabled).toBe(true);
  await user.click(screen.getByRole('button', { name: 'Text', exact: true }));
  expect(fetch.mock.calls[0][1].signal.aborted).toBe(true);
  resolve(png());
  await waitFor(() => expect(screen.queryByRole('link', { name: 'Download PNG' })).toBeNull());
  expect(screen.getByRole('button', { name: 'Generate QR code' }).disabled).toBe(false);
});
test('renders server errors and revokes preview URLs on unmount', async () => {
  const user = userEvent.setup();
  fetch.mockResolvedValueOnce(new Response(JSON.stringify({ error: 'Choose stronger contrast.' }), { status: 400, headers: { 'content-type': 'application/json' } }));
  const view = render(<Generator />);
  await user.type(screen.getByLabelText('Website link'), 'https://example.com');
  await user.click(screen.getByRole('button', { name: 'Generate QR code' }));
  expect((await screen.findByRole('alert')).textContent).toContain('stronger contrast');
  await user.click(screen.getByRole('button', { name: 'Generate QR code' }));
  await screen.findByRole('link', { name: 'Download PNG' });
  view.unmount();
  expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:qr-preview');
});
